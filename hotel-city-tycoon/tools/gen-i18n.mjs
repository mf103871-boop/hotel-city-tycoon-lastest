for (const r of rooms) {
  put(`room.${r.id}.name`, ROOM_EN[r.id] ?? human(r.id), ROOM_AR[r.id]);
  const [de, da] = ROOM_DESC[r.id] ?? [`${human(r.id)} room.`, null];
  put(`room.${r.id}.desc`, de, da);
}
for (const d of decor) {
  const name = d.id.slice(d.category.length + 1);
  put(`decor.${d.id}.name`, `${human(name)} ${human(d.category)}`.trim(),
      `${CAT_AR[d.category] ?? d.category} ${human(name)}`);
}
for (const s of staff.roles) put(`staff.${s.id}.name`, human(s.id), STAFF_AR[s.id]);
for (const g of staff.grades) put(`staff.grade.${g.id}`, human(g.id),
  {bronze:'برونزي',silver:'فضي',gold:'ذهبي'}[g.id]);
for (const g of guests) put(`guest.${g.id}.name`, human(g.id), GUEST_AR[g.id]);
for (const s of shifts) {
  const h = s.durationSec/3600;
  put(`shift.${h}h`, `${h} hours`, `${h} ${h===2?'ساعتان':h<11?'ساعات':'ساعة'}`);
}
for (const e of events) put(`event.${e.id}.name`, human(e.id), EVENT_AR[e.id]);

